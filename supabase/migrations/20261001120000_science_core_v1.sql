create or replace function internal.guard_experiment()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare control_count integer; candidate_count integer; unfrozen_models integer;
begin
  if tg_op = 'DELETE' then
    if old.frozen_at is not null then raise exception 'frozen experiment % cannot be deleted', old.id; end if;
    return old;
  end if;
  if old.frozen_at is not null then
    if (to_jsonb(new) - array['status','completed_at']) <> (to_jsonb(old) - array['status','completed_at']) then
      raise exception 'experiment % preregistration is frozen; only lifecycle status may change', old.id;
    end if;
    if old.status = 'FROZEN' and new.status not in ('FROZEN','RUNNING','ABORTED') then raise exception 'invalid experiment transition % -> %', old.status, new.status;
    elsif old.status = 'RUNNING' and new.status not in ('RUNNING','COMPLETED','ABORTED') then raise exception 'invalid experiment transition % -> %', old.status, new.status;
    elsif old.status in ('COMPLETED','ABORTED') and new.status <> old.status then raise exception 'terminal experiment status % cannot transition', old.status;
    end if;
    if new.status = 'COMPLETED' and new.completed_at is null then raise exception 'completed experiment requires completed_at'; end if;
    return new;
  end if;
  if old.frozen_at is null and new.frozen_at is not null then
    if new.status <> 'FROZEN' then raise exception 'experiment must enter FROZEN status when preregistration is frozen'; end if;
    if new.pre_registration = '{}'::jsonb then raise exception 'experiment preregistration cannot be empty'; end if;
    select count(*) filter (where em.role = 'CONTROL'), count(*) filter (where em.role in ('CHAMPION','CHALLENGER')), count(*) filter (where mv.frozen_at is null)
      into control_count, candidate_count, unfrozen_models
    from public.experiment_models em join public.model_versions mv on mv.id = em.model_version_id
    where em.experiment_id = new.id;
    if control_count < 1 or candidate_count < 1 then raise exception 'experiment % requires at least one candidate and one control model', new.id; end if;
    if unfrozen_models > 0 then raise exception 'all experiment model versions must be frozen before preregistration freeze'; end if;
  end if;
  return new;
end;
$$;
create trigger experiment_guard before update or delete on public.experiments for each row execute function internal.guard_experiment();

create or replace function internal.log_experiment_transition()
returns trigger language plpgsql security invoker set search_path = '' as $$
