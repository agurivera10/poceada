create or replace function internal.guard_portfolio()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare run_frozen timestamptz; ticket_count integer; bad_ticket_count integer; total_cost numeric; ticket_blob text;
begin
  if tg_op = 'DELETE' then
    if old.frozen_at is not null then raise exception 'frozen portfolio % cannot be deleted', old.id; end if;
    return old;
  end if;
  if old.frozen_at is not null then raise exception 'frozen portfolio % cannot be modified', old.id; end if;
  if old.frozen_at is null and new.frozen_at is not null then
    select r.frozen_at into run_frozen from public.model_runs r where r.id = new.run_id;
    if run_frozen is null then raise exception 'portfolio requires a frozen model run'; end if;
    select count(*), coalesce(sum(t.cost_ars),0), count(*) filter (where coalesce(n.number_count,0) <> 5), string_agg(t.ticket_index::text || ':' || coalesce(n.numbers_text,''), '|' order by t.ticket_index)
      into ticket_count, total_cost, bad_ticket_count, ticket_blob
    from public.tickets t
    left join lateral (
      select count(*) as number_count, string_agg(tn.number::text, ',' order by tn.position) as numbers_text
      from public.ticket_numbers tn where tn.ticket_id = t.id
    ) n on true
    where t.portfolio_id = new.id;
    if ticket_count < 1 or bad_ticket_count > 0 then raise exception 'portfolio % requires at least one ticket and exactly 5 numbers per ticket', new.id; end if;
    if total_cost <> new.budget_ars then raise exception 'portfolio % budget % must equal committed ticket cost %', new.id, new.budget_ars, total_cost; end if;
    if exists (select 1 from public.tickets t where t.portfolio_id = new.id and t.cost_ars <> new.ticket_price_ars) then raise exception 'all tickets must use portfolio ticket_price_ars'; end if;
    new.portfolio_sha256 := internal.sha256_hex(new.run_id::text || '|' || new.strategy || '|' || new.ticket_price_ars::text || '|' || new.budget_ars::text || '|' || new.optimizer_seed::text || '|' || new.config::text || '|' || coalesce(ticket_blob,''));
  end if;
  return new;
end;
$$;
create trigger portfolio_guard before update or delete on public.portfolios for each row execute function internal.guard_portfolio();

create view public.science_run_integrity with (security_invoker = true) as
select
  r.id as run_id, r.experiment_id, r.model_version_id, r.run_kind, r.target_draw_number, r.trained_through_draw_number, r.frozen_at,
  count(p.number)::integer as prediction_count, count(p.probability)::integer as probability_count, sum(p.probability) as probability_sum,
  (r.trained_through_draw_number < r.target_draw_number) as leakage_cutoff_ok,
  (r.dataset_sha256 is not null and r.features_sha256 is not null and r.run_hash is not null) as hashes_complete,
  (r.frozen_at is not null and count(p.number) = 100 and count(p.probability) = 100 and abs(coalesce(sum(p.probability),0) - 10.0) <= 0.000000001 and r.trained_through_draw_number < r.target_draw_number and r.dataset_sha256 is not null and r.features_sha256 is not null and r.run_hash is not null) as science_core_valid
from public.model_runs r
left join public.model_predictions p on p.run_id = r.id
group by r.id;

create view public.science_core_status with (security_invoker = true) as
select
  (select count(*) from public.experiments) as experiments,
  (select count(*) from public.experiments where frozen_at is not null) as frozen_experiments,
  (select count(*) from public.dataset_snapshots where frozen_at is not null) as frozen_dataset_snapshots,
  (select count(*) from public.feature_snapshots where frozen_at is not null) as frozen_feature_snapshots,
  (select count(*) from public.model_runs where frozen_at is not null) as frozen_runs,
  (select count(*) from public.science_run_integrity where frozen_at is not null and not science_core_valid) as invalid_frozen_runs,
  (select count(*) from public.portfolios where frozen_at is not null) as frozen_portfolios;

