create or replace function internal.guard_feature_snapshot_header()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare n integer; min_num integer; max_num integer; rows_blob text; ds_through integer; ds_frozen timestamptz;
begin
  if tg_op = 'DELETE' then
    if old.frozen_at is not null then raise exception 'frozen feature snapshot % cannot be deleted', old.id; end if;
    return old;
  end if;
  if old.frozen_at is not null then raise exception 'frozen feature snapshot % cannot be modified', old.id; end if;
  if old.frozen_at is null and new.frozen_at is not null then
    select d.through_draw_number, d.frozen_at into ds_through, ds_frozen from public.dataset_snapshots d where d.id = new.dataset_snapshot_id;
    if ds_frozen is null or ds_through <> new.trained_through_draw_number then
      raise exception 'feature snapshot % dataset must be frozen exactly through trained draw %', new.id, new.trained_through_draw_number;
    end if;
    select count(*), min(v.number), max(v.number), string_agg(v.row_sha256, '' order by v.number) into n, min_num, max_num, rows_blob
    from public.feature_snapshot_values v where v.snapshot_id = new.id;
    if n <> 100 or min_num <> 0 or max_num <> 99 then
      raise exception 'feature snapshot % requires exactly numbers 00..99; got count %, min %, max %', new.id, n, min_num, max_num;
    end if;
    new.snapshot_sha256 := internal.sha256_hex(new.target_draw_number::text || '|' || new.trained_through_draw_number::text || '|' || new.dataset_snapshot_id::text || '|' || new.feature_version || '|' || new.feature_config::text || '|' || new.git_commit_sha || '|' || coalesce(rows_blob, ''));
  end if;
  return new;
end;
$$;
create trigger feature_snapshot_header_guard before update or delete on public.feature_snapshots for each row execute function internal.guard_feature_snapshot_header();

