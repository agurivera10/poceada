create or replace function internal.sha256_hex(p_text text)
returns text language sql immutable security invoker set search_path = '' as $$
  select pg_catalog.encode(extensions.digest(pg_catalog.convert_to(p_text, 'UTF8'), 'sha256'), 'hex');
$$;
revoke execute on function internal.sha256_hex(text) from public, anon, authenticated;
grant execute on function internal.sha256_hex(text) to service_role;

create or replace function internal.prepare_dataset_snapshot_draw()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare distinct_count integer; in_range boolean;
begin
  select count(distinct x), bool_and(x between 0 and 99) into distinct_count, in_range
  from pg_catalog.unnest(new.numbers) as x;
  if pg_catalog.cardinality(new.numbers) <> 10 or distinct_count <> 10 or not coalesce(in_range, false) then
    raise exception 'dataset snapshot draw % must contain exactly 10 unique numbers in 0..99', new.draw_number;
  end if;
  new.row_sha256 := internal.sha256_hex(new.draw_number::text || '|' || new.draw_date::text || '|' || new.validation_status || '|' || pg_catalog.array_to_string(new.numbers, ','));
  return new;
end;
$$;

create or replace function internal.guard_dataset_snapshot_draw_change()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare sid uuid; frozen timestamptz;
begin
  sid := case when tg_op = 'DELETE' then old.snapshot_id else new.snapshot_id end;
  select s.frozen_at into frozen from public.dataset_snapshots s where s.id = sid;
  if frozen is not null then raise exception 'dataset snapshot % is frozen and immutable', sid; end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
create trigger dataset_snapshot_draw_guard before insert or update or delete on public.dataset_snapshot_draws for each row execute function internal.guard_dataset_snapshot_draw_change();
create trigger dataset_snapshot_draw_prepare before insert or update on public.dataset_snapshot_draws for each row execute function internal.prepare_dataset_snapshot_draw();

create or replace function internal.guard_dataset_snapshot_header()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare n integer; max_draw integer; rows_blob text;
begin
  if tg_op = 'DELETE' then
    if old.frozen_at is not null then raise exception 'frozen dataset snapshot % cannot be deleted', old.id; end if;
    return old;
  end if;
  if old.frozen_at is not null then raise exception 'frozen dataset snapshot % cannot be modified', old.id; end if;
  if old.frozen_at is null and new.frozen_at is not null then
    select count(*), max(d.draw_number), string_agg(d.row_sha256, '' order by d.draw_number) into n, max_draw, rows_blob
    from public.dataset_snapshot_draws d where d.snapshot_id = new.id;
    if n = 0 or max_draw <> new.through_draw_number then
      raise exception 'dataset snapshot % cannot freeze: rows %, max draw %, expected through %', new.id, n, max_draw, new.through_draw_number;
    end if;
    new.draw_count := n;
    new.dataset_sha256 := internal.sha256_hex(new.through_draw_number::text || '|' || new.manifest::text || '|' || coalesce(rows_blob, ''));
  end if;
  return new;
end;
$$;
create trigger dataset_snapshot_header_guard before update or delete on public.dataset_snapshots for each row execute function internal.guard_dataset_snapshot_header();

