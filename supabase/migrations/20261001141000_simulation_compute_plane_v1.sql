create table public.simulation_jobs (
  id uuid primary key default gen_random_uuid(),
  simulation_experiment_id uuid not null references public.simulation_experiments(id) on delete cascade,
  parent_job_id uuid references public.simulation_jobs(id) on delete set null,
  preset_slug text references public.simulation_presets(slug) on delete set null,
  status text not null default 'QUEUED' check (status in ('QUEUED','CLAIMED','RUNNING','CANCELLING','CANCELLED','COMPLETED','FAILED','STALE')),
  priority smallint not null default 50 check (priority between 0 and 100),
  requested_iterations bigint not null check (requested_iterations > 0 and requested_iterations <= 1000000000),
  progress_iterations bigint not null default 0 check (progress_iterations >= 0),
  seed_base bigint not null,
  config jsonb not null default '{}'::jsonb check (jsonb_typeof(config)='object'),
  current_phase text,
  worker_id text,
  attempt integer not null default 1 check (attempt between 1 and 20),
  max_attempts integer not null default 3 check (max_attempts between 1 and 20),
  cancel_requested boolean not null default false,
  heartbeat_at timestamptz,
  lease_expires_at timestamptz,
  runtime_ms bigint check (runtime_ms is null or runtime_ms >= 0),
  result_summary jsonb not null default '{}'::jsonb check (jsonb_typeof(result_summary)='object'),
  result_sha256 text check (result_sha256 is null or result_sha256 ~ '^[0-9a-f]{64}$'),
  error_code text,
  error_message text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  check (progress_iterations <= requested_iterations)
);

create table public.simulation_workers (
  id text primary key,
  display_name text not null,
  worker_version text not null,
  engine_version text not null,
  status text not null default 'ONLINE' check (status in ('ONLINE','BUSY','DRAINING','OFFLINE')),
  capabilities jsonb not null default '{}'::jsonb check (jsonb_typeof(capabilities)='object'),
  cpu_count integer check (cpu_count is null or cpu_count > 0),
  memory_mb integer check (memory_mb is null or memory_mb > 0),
  current_job_id uuid references public.simulation_jobs(id) on delete set null,
  last_seen_at timestamptz not null default now(),
  started_at timestamptz not null default now(),
  completed_jobs integer not null default 0 check (completed_jobs >= 0),
  failed_jobs integer not null default 0 check (failed_jobs >= 0)
);

create table public.simulation_job_events (
  id bigint generated by default as identity primary key,
  job_id uuid not null references public.simulation_jobs(id) on delete cascade,
  event_type text not null,
  message text,
  data jsonb not null default '{}'::jsonb check (jsonb_typeof(data)='object'),
  created_at timestamptz not null default now()
);

create index simulation_jobs_queue_idx on public.simulation_jobs(status, priority desc, created_at) where status='QUEUED';
create index simulation_jobs_experiment_idx on public.simulation_jobs(simulation_experiment_id, created_at desc);
create index simulation_jobs_worker_idx on public.simulation_jobs(worker_id, status) where worker_id is not null;
create index simulation_jobs_lease_idx on public.simulation_jobs(lease_expires_at) where status in ('CLAIMED','RUNNING','CANCELLING');
create index simulation_jobs_parent_idx on public.simulation_jobs(parent_job_id) where parent_job_id is not null;
create index simulation_workers_job_idx on public.simulation_workers(current_job_id) where current_job_id is not null;
create index simulation_job_events_job_idx on public.simulation_job_events(job_id, created_at desc);

