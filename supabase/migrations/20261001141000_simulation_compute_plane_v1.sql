create view public.simulation_compute_status with (security_invoker=true) as
select
 (select count(*) from public.simulation_jobs where status='QUEUED') queued_jobs,
 (select count(*) from public.simulation_jobs where status in ('CLAIMED','RUNNING','CANCELLING')) active_jobs,
 (select count(*) from public.simulation_jobs where status='COMPLETED') completed_jobs,
 (select count(*) from public.simulation_jobs where status='FAILED') failed_jobs,
 (select coalesce(sum(progress_iterations),0) from public.simulation_jobs where status in ('CLAIMED','RUNNING','CANCELLING')) processed_iterations,
 (select count(*) from public.simulation_workers where status in ('ONLINE','BUSY') and last_seen_at>now()-interval '5 minutes') online_workers,
 (select count(*) from public.simulation_workers where status='BUSY' and last_seen_at>now()-interval '5 minutes') busy_workers,
 (select coalesce(sum(progress_iterations),0) from public.simulation_jobs where status in ('CLAIMED','RUNNING','CANCELLING')) active_progress_iterations;
grant select on public.simulation_compute_status to anon,authenticated,service_role;

