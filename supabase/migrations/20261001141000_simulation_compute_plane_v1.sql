create or replace function public.create_simulation_job(p_name text,p_preset_slug text,p_requested_iterations bigint,p_seed_base bigint,p_config jsonb,p_git_commit_sha text,p_priority integer default 50)
returns public.simulation_jobs language plpgsql security invoker set search_path='' as $$
declare v_preset public.simulation_presets%rowtype; v_experiment_id uuid; v_job public.simulation_jobs%rowtype; v_slug text;
begin
  if p_requested_iterations is null or p_requested_iterations < 1 or p_requested_iterations > 1000000000 then raise exception 'requested_iterations must be between 1 and 1,000,000,000'; end if;
  if p_git_commit_sha is null or p_git_commit_sha !~ '^[0-9a-f]{40}([0-9a-f]{24})?$' then raise exception 'valid git commit sha is required'; end if;
  select * into v_preset from public.simulation_presets where slug=p_preset_slug and active=true;
  if not found then raise exception 'unknown or inactive preset %',p_preset_slug; end if;
  v_slug:='app-'||to_char(clock_timestamp(),'YYYYMMDDHH24MISSMS')||'-'||substr(gen_random_uuid()::text,1,8);
  insert into public.simulation_experiments(slug,name,preset_slug,category,hypothesis,engine_version,git_commit_sha,config,requested_iterations,seed_base,shard_count,status)
  values(v_slug,coalesce(nullif(trim(p_name),''),v_preset.name),v_preset.slug,v_preset.category,'App-launched simulation; interpretation follows the frozen preset and configuration.',v_preset.engine_version,p_git_commit_sha,coalesce(v_preset.default_config,'{}'::jsonb)||coalesce(p_config,'{}'::jsonb),p_requested_iterations,p_seed_base,1,'DRAFT') returning id into v_experiment_id;
  update public.simulation_experiments set status='FROZEN',frozen_at=now() where id=v_experiment_id;
  insert into public.simulation_jobs(simulation_experiment_id,preset_slug,status,priority,requested_iterations,seed_base,config)
  values(v_experiment_id,v_preset.slug,'QUEUED',greatest(0,least(100,coalesce(p_priority,50))),p_requested_iterations,p_seed_base,coalesce(v_preset.default_config,'{}'::jsonb)||coalesce(p_config,'{}'::jsonb)) returning * into v_job;
  update public.simulation_experiments set status='QUEUED' where id=v_experiment_id;
  insert into public.simulation_job_events(job_id,event_type,message,data) values(v_job.id,'QUEUED','Simulation queued from app',jsonb_build_object('preset',v_preset.slug,'iterations',p_requested_iterations,'seed',p_seed_base));
  return v_job;
end $$;

create or replace function public.claim_simulation_job(p_worker_id text,p_lease_seconds integer default 120)
returns setof public.simulation_jobs language plpgsql security invoker set search_path='' as $$
declare v_job public.simulation_jobs%rowtype;
begin
  with next_job as (select id from public.simulation_jobs where status='QUEUED' and cancel_requested=false order by priority desc,created_at asc for update skip locked limit 1)
  update public.simulation_jobs j set status='CLAIMED',worker_id=p_worker_id,started_at=coalesce(j.started_at,now()),heartbeat_at=now(),lease_expires_at=now()+make_interval(secs=>greatest(30,least(900,p_lease_seconds))),current_phase='claim',updated_at=now() from next_job n where j.id=n.id returning j.* into v_job;
  if v_job.id is null then return; end if;
  update public.simulation_experiments set status='RUNNING' where id=v_job.simulation_experiment_id;
  update public.simulation_workers set status='BUSY',current_job_id=v_job.id,last_seen_at=now() where id=p_worker_id;
  insert into public.simulation_job_events(job_id,event_type,message,data) values(v_job.id,'CLAIMED','Job claimed by worker',jsonb_build_object('worker_id',p_worker_id));
  return next v_job;
end $$;

create or replace function public.heartbeat_simulation_job(p_job_id uuid,p_worker_id text,p_progress_iterations bigint,p_phase text,p_lease_seconds integer default 120,p_partial_summary jsonb default '{}'::jsonb)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare v_job public.simulation_jobs%rowtype;
begin
  update public.simulation_jobs j set progress_iterations=least(j.requested_iterations,greatest(j.progress_iterations,coalesce(p_progress_iterations,j.progress_iterations))),current_phase=coalesce(p_phase,j.current_phase),status=case when j.cancel_requested then 'CANCELLING' else 'RUNNING' end,heartbeat_at=now(),lease_expires_at=now()+make_interval(secs=>greatest(30,least(900,p_lease_seconds))),result_summary=j.result_summary||coalesce(p_partial_summary,'{}'::jsonb),updated_at=now()
  where j.id=p_job_id and j.worker_id=p_worker_id and j.status in ('CLAIMED','RUNNING','CANCELLING') returning j.* into v_job;
  if v_job.id is null then raise exception 'job not owned by worker or not running'; end if;
  update public.simulation_workers set status='BUSY',current_job_id=p_job_id,last_seen_at=now() where id=p_worker_id;
  return jsonb_build_object('job_id',v_job.id,'status',v_job.status,'cancel_requested',v_job.cancel_requested,'progress_iterations',v_job.progress_iterations,'requested_iterations',v_job.requested_iterations);
end $$;

create or replace function public.complete_simulation_job(p_job_id uuid,p_worker_id text,p_result_sha256 text,p_result_summary jsonb default '{}'::jsonb,p_runtime_ms bigint default null)
returns public.simulation_jobs language plpgsql security invoker set search_path='' as $$
declare v_job public.simulation_jobs%rowtype;
begin
  if p_result_sha256 !~ '^[0-9a-f]{64}$' then raise exception 'invalid result sha256'; end if;
  update public.simulation_jobs j set status='COMPLETED',progress_iterations=j.requested_iterations,current_phase='complete',result_sha256=p_result_sha256,result_summary=j.result_summary||coalesce(p_result_summary,'{}'::jsonb),runtime_ms=coalesce(p_runtime_ms,j.runtime_ms),completed_at=now(),heartbeat_at=now(),lease_expires_at=null,updated_at=now()
  where j.id=p_job_id and j.worker_id=p_worker_id and j.status in ('CLAIMED','RUNNING','CANCELLING') and not j.cancel_requested returning j.* into v_job;
  if v_job.id is null then raise exception 'job cannot be completed'; end if;
  update public.simulation_experiments set status='COMPLETED',completed_at=now() where id=v_job.simulation_experiment_id;
  update public.simulation_workers set status='ONLINE',current_job_id=null,last_seen_at=now(),completed_jobs=completed_jobs+1 where id=p_worker_id;
  insert into public.simulation_job_events(job_id,event_type,message,data) values(v_job.id,'COMPLETED','Simulation completed',jsonb_build_object('worker_id',p_worker_id,'result_sha256',p_result_sha256,'runtime_ms',p_runtime_ms));
  return v_job;
end $$;

create or replace function public.fail_simulation_job(p_job_id uuid,p_worker_id text,p_error_code text,p_error_message text,p_runtime_ms bigint default null)
returns public.simulation_jobs language plpgsql security invoker set search_path='' as $$
declare v_job public.simulation_jobs%rowtype;
begin
  update public.simulation_jobs j set status='FAILED',error_code=left(coalesce(p_error_code,'WORKER_ERROR'),100),error_message=left(coalesce(p_error_message,'Unknown worker error'),4000),runtime_ms=coalesce(p_runtime_ms,j.runtime_ms),completed_at=now(),heartbeat_at=now(),lease_expires_at=null,current_phase='failed',updated_at=now()
  where j.id=p_job_id and j.worker_id=p_worker_id and j.status in ('CLAIMED','RUNNING','CANCELLING') returning j.* into v_job;
  if v_job.id is null then raise exception 'job cannot be failed'; end if;
  update public.simulation_experiments set status='FAILED',completed_at=now() where id=v_job.simulation_experiment_id;
  update public.simulation_workers set status='ONLINE',current_job_id=null,last_seen_at=now(),failed_jobs=failed_jobs+1 where id=p_worker_id;
  insert into public.simulation_job_events(job_id,event_type,message,data) values(v_job.id,'FAILED','Simulation failed',jsonb_build_object('worker_id',p_worker_id,'error_code',p_error_code));
  return v_job;
end $$;

create or replace function public.request_cancel_simulation_job(p_job_id uuid)
returns public.simulation_jobs language plpgsql security invoker set search_path='' as $$
declare v_job public.simulation_jobs%rowtype;
begin
  update public.simulation_jobs j set cancel_requested=true,status=case when j.status='QUEUED' then 'CANCELLED' else 'CANCELLING' end,completed_at=case when j.status='QUEUED' then now() else j.completed_at end,current_phase=case when j.status='QUEUED' then 'cancelled' else 'cancelling' end,updated_at=now()
  where j.id=p_job_id and j.status in ('QUEUED','CLAIMED','RUNNING') returning j.* into v_job;
  if v_job.id is null then raise exception 'job cannot be cancelled'; end if;
  if v_job.status='CANCELLED' then update public.simulation_experiments set status='ABORTED',completed_at=now() where id=v_job.simulation_experiment_id; end if;
  insert into public.simulation_job_events(job_id,event_type,message) values(v_job.id,'CANCEL_REQUESTED','Cancellation requested');
  return v_job;
end $$;

create or replace function public.acknowledge_cancelled_simulation_job(p_job_id uuid,p_worker_id text,p_runtime_ms bigint default null)
returns public.simulation_jobs language plpgsql security invoker set search_path='' as $$
declare v_job public.simulation_jobs%rowtype;
begin
  update public.simulation_jobs j set status='CANCELLED',completed_at=now(),lease_expires_at=null,current_phase='cancelled',runtime_ms=coalesce(p_runtime_ms,j.runtime_ms),updated_at=now() where j.id=p_job_id and j.worker_id=p_worker_id and j.cancel_requested=true and j.status='CANCELLING' returning j.* into v_job;
  if v_job.id is null then raise exception 'job cannot acknowledge cancellation'; end if;
  update public.simulation_experiments set status='ABORTED',completed_at=now() where id=v_job.simulation_experiment_id;
  update public.simulation_workers set status='ONLINE',current_job_id=null,last_seen_at=now() where id=p_worker_id;
  insert into public.simulation_job_events(job_id,event_type,message,data) values(v_job.id,'CANCELLED','Worker stopped simulation',jsonb_build_object('worker_id',p_worker_id));
  return v_job;
end $$;

create or replace function public.retry_simulation_job(p_job_id uuid)
returns public.simulation_jobs language plpgsql security invoker set search_path='' as $$
declare v_old public.simulation_jobs%rowtype; v_new public.simulation_jobs%rowtype;
begin
  select * into v_old from public.simulation_jobs where id=p_job_id for update;
  if not found or v_old.status not in ('FAILED','CANCELLED','STALE') then raise exception 'only failed/cancelled/stale jobs can be retried'; end if;
  if v_old.attempt>=v_old.max_attempts then raise exception 'max attempts reached'; end if;
  insert into public.simulation_jobs(simulation_experiment_id,parent_job_id,preset_slug,status,priority,requested_iterations,seed_base,config,attempt,max_attempts) values(v_old.simulation_experiment_id,v_old.id,v_old.preset_slug,'QUEUED',v_old.priority,v_old.requested_iterations,v_old.seed_base,v_old.config,v_old.attempt+1,v_old.max_attempts) returning * into v_new;
  update public.simulation_experiments set status='QUEUED',completed_at=null where id=v_old.simulation_experiment_id;
  insert into public.simulation_job_events(job_id,event_type,message,data) values(v_new.id,'RETRY_QUEUED','Retry queued',jsonb_build_object('parent_job_id',v_old.id,'attempt',v_new.attempt));
  return v_new;
end $$;

create or replace function public.mark_stale_simulation_jobs()
returns integer language plpgsql security invoker set search_path='' as $$
declare v_count integer;
begin
  with stale as (update public.simulation_jobs j set status='STALE',completed_at=now(),current_phase='stale',error_code='LEASE_EXPIRED',error_message='Worker heartbeat lease expired',updated_at=now() where j.status in ('CLAIMED','RUNNING','CANCELLING') and j.lease_expires_at<now() returning j.id)
  select count(*) into v_count from stale;
  update public.simulation_workers w set status='OFFLINE',current_job_id=null where w.current_job_id in (select id from public.simulation_jobs where status='STALE');
  return v_count;
end $$;

